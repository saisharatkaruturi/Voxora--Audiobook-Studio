"""Real reader ratings for published books, from Open Library (free, no key).

Ratings are never generated by the AI model: either a public catalogue has them,
or the book shows "no ratings found". Lookups are cached in memory for a day.
"""

from __future__ import annotations

import re
import threading
import time

import httpx

from app.core.logging import get_logger

log = get_logger(__name__)

SEARCH_URL = "https://openlibrary.org/search.json"
FIELDS = "key,title,author_name,ratings_average,ratings_count,first_publish_year,cover_i"
USER_AGENT = "VOXORA-Audiobook-Studio/1.0 (book ratings lookup)"
TTL = 24 * 3600

_cache: dict[tuple[str, str], tuple[float, dict | None]] = {}
_lock = threading.Lock()


def _squash(text: str | None) -> str:
    return re.sub(r"[^a-z0-9]", "", (text or "").lower())


def _title_matches(wanted: str, found: str) -> bool:
    a, b = _squash(wanted), _squash(found)
    return bool(a and b) and (a == b or a in b or b in a)


def _author_matches(wanted: str | None, names: list[str] | None) -> bool:
    if not wanted:
        return True
    last = _squash(wanted.split()[-1]) if wanted.split() else ""
    return any(last and last in _squash(n) for n in names or [])


def _search(params: dict) -> list[dict]:
    r = httpx.get(SEARCH_URL, params={**params, "fields": FIELDS, "limit": 8}, headers={"User-Agent": USER_AGENT}, timeout=12)
    r.raise_for_status()
    return r.json().get("docs") or []


def lookup(title: str, author: str | None = None) -> dict | None:
    """{average, count, source, url, year, cover_url} for the best-matching work, or None.

    Among the works whose title and author match, the one with the most ratings wins
    (that's the main edition, not a box set or a study guide)."""
    title = (title or "").strip()
    if not title:
        return None
    key = (_squash(title), _squash(author))
    with _lock:
        hit = _cache.get(key)
        if hit and time.time() - hit[0] < TTL:
            return hit[1]
    result = None
    try:
        docs = _search({"title": title, "author": author} if author else {"title": title})
        if not docs and author:
            docs = _search({"q": f"{title} {author}"})
        candidates = [d for d in docs if _title_matches(title, d.get("title", "")) and _author_matches(author, d.get("author_name"))]
        if candidates:
            best = max(candidates, key=lambda d: d.get("ratings_count") or 0)
            result = {
                "average": round(float(best["ratings_average"]), 2) if best.get("ratings_average") else None,
                "count": int(best.get("ratings_count") or 0),
                "source": "Open Library",
                "url": f"https://openlibrary.org{best['key']}" if best.get("key") else None,
                "year": best.get("first_publish_year"),
                "cover_url": f"https://covers.openlibrary.org/b/id/{best['cover_i']}-M.jpg" if best.get("cover_i") else None,
            }
    except (httpx.HTTPError, ValueError) as exc:
        log.warning("ratings.lookup_failed", title=title, error=type(exc).__name__)
        return None  # don't cache network failures
    with _lock:
        if len(_cache) > 2000:
            _cache.clear()
        _cache[key] = (time.time(), result)
    return result
